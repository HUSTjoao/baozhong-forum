"""Build locally hosted, unicode-ranged Chinese fonts from licensed repo assets."""
from collections import Counter
import hashlib
import json
from pathlib import Path
import re
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'public/fonts/site'
DEST.mkdir(parents=True, exist_ok=True)
text = ''.join(p.read_text(encoding='utf-8') for folder in ['app', 'components', 'data']
               for p in (ROOT / folder).rglob('*') if p.suffix in {'.tsx', '.ts', '.json'})
frequency = Counter(ord(c) for c in text if '\u3400' <= c <= '\u9fff')
sources = [('Site WenKai', 'profile-reading-wenkai.woff')]

def ranges(points):
    result = []
    start = last = None
    for point in sorted(points):
        if last is not None and point == last + 1:
            last = point
        else:
            if start is not None:
                result.append(f'U+{start:X}' + (f'-{last:X}' if last != start else ''))
            start = last = point
    if start is not None:
        result.append(f'U+{start:X}' + (f'-{last:X}' if last != start else ''))
    return ','.join(result)

rules = ['/* Generated by scripts/build-site-fonts.py. Shared glyphs, no per-page subsets. */']
manifest = []
for family, filename in ([] if '--refresh-ui' in sys.argv else sources):
    source = ROOT / 'public/fonts' / filename
    font = TTFont(source)
    points = set(font.getBestCmap())
    # Small Latin/punctuation shard and frequency-ordered Chinese shards. Only
    # shards containing text actually displayed on the page are downloaded.
    latin = {p for p in points if p < 0x300 or 0x2000 <= p <= 0x206f}
    common = [p for p, _ in frequency.most_common() if p in points - latin]
    ordered = common + sorted(points - latin - set(common))
    groups = [sorted(latin)] + [ordered[i:i + 512] for i in range(0, len(ordered), 512)]
    record = {'family': family, 'source': filename, 'glyphs': len(points), 'shards': []}
    for index, group in enumerate(groups):
        part = TTFont(source)
        options = subset.Options()
        options.flavor = 'woff2'
        worker = subset.Subsetter(options=options)
        worker.populate(unicodes=group)
        worker.subset(part)
        part.flavor = 'woff2'
        stem = family.lower().replace(' ', '-') + f'-{index:02d}'
        temporary = DEST / (stem + '.woff2')
        part.save(temporary)
        blob = temporary.read_bytes()
        name = stem + '-' + hashlib.sha256(blob).hexdigest()[:12] + '.woff2'
        temporary.replace(DEST / name)
        rules.append(f"@font-face{{font-family:'{family}';src:url('/fonts/site/{name}') format('woff2');font-style:normal;font-weight:400;font-display:swap;unicode-range:{ranges(group)}}}")
        record['shards'].append({'file': name, 'bytes': len(blob), 'unicodeRange': ranges(group)})
    manifest.append(record)
    print(family, len(points), 'characters,', len(groups), 'shards,', sum(p['bytes'] for p in record['shards']), 'bytes')
if '--refresh-ui' in sys.argv:
    manifest = json.loads((ROOT / 'data/site-fonts.json').read_text(encoding='utf-8'))
    rules = [rules[0]]
    for record in manifest:
        record['shards'] = [part for part in record['shards'] if not part.get('priority')]
        for part in record['shards']:
            rules.append(f"@font-face{{font-family:'{record['family']}';src:url('/fonts/site/{part['file']}') format('woff2');font-style:normal;font-weight:400;font-display:swap;unicode-range:{part['unicodeRange']}}}")

# The small homepage/UI set takes precedence over general-purpose shards, so
# one common symbol or uncommon campus word cannot pull in a large rare shard.
ui_points = set()
for name in ['admission-wenkai.woff2', 'admission-sans.ttf', 'countdown-serif.woff2',
             'baozhong-title.ttf', 'baozhong-navigation.ttf', 'baozhong-dock.ttf',
             'baozhong-explore.ttf', 'home-description-serif.woff']:
    ui_points.update(TTFont(ROOT / 'public/fonts' / name).getBestCmap())
for name in ['UniversityJourney', 'AdmissionLetter', 'GaokaoTimeline', 'CampusFrames',
             'CampusPhotoUpload', 'Navbar', 'Footer']:
    ui_points.update(ord(c) for c in (ROOT / 'components' / (name + '.tsx')).read_text(encoding='utf-8'))
for name in ['campus-collection.json', 'countdown-slogans.ts', 'study-prompts.ts']:
    path = ROOT / 'data' / name
    if path.exists():
        ui_points.update(ord(c) for c in path.read_text(encoding='utf-8'))
for record in manifest:
    source = ROOT / 'public/fonts' / record['source']
    font = TTFont(source, recalcTimestamp=False)
    group = set(font.getBestCmap()) & ui_points
    worker = subset.Subsetter(options=subset.Options())
    worker.populate(unicodes=group)
    worker.subset(font)
    font.flavor = 'woff2'
    stem = record['family'].lower().replace(' ', '-') + '-ui'
    temporary = DEST / (stem + '.woff2')
    font.save(temporary)
    blob = temporary.read_bytes()
    name = stem + '-' + hashlib.sha256(blob).hexdigest()[:12] + '.woff2'
    temporary.replace(DEST / name)
    part = {'file': name, 'bytes': len(blob), 'unicodeRange': ranges(group), 'priority': True}
    record['shards'].append(part)
    rules.append(f"@font-face{{font-family:'{record['family']}';src:url('/fonts/site/{name}') format('woff2');font-style:normal;font-weight:400;font-display:swap;unicode-range:{part['unicodeRange']}}}")
    print(record['family'], 'UI:', len(group), 'characters,', len(blob), 'bytes', flush=True)
(ROOT / 'app/site-fonts.css').write_text('\n'.join(rules) + '\n', encoding='utf-8')
(ROOT / 'data/site-fonts.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
