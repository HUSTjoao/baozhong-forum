const fallback: Record<MajorCategory, string> = { arts: 'humanities', science: 'physical', engineering: 'machinery', medicine: 'medicine', other: 'creative' }

export function getMajorExploration(major: Major): MajorExploration {
  const code = major.officialCode ?? ''
  const prefix = code.slice(0, 4)
  if (code === '082007T') return profiles.airworthiness
  if (['082009T', '140003TK'].includes(code)) return profiles.aerialSystems
  if (['080214T', '080216T'].includes(code)) return profiles.smartMobility
  if (code === '140011TK') return profiles.medicalEngineering
  if (code === '101006') return profiles.dentalTechnology
  if (code === '040206T') return profiles.sportsRehabilitation
  if (code === '080414T') return profiles.materials
  if (code.startsWith('0402')) return profiles.sport
  if (code.startsWith('09')) return profiles.agriculture
  if (code.startsWith('13')) return profiles.creative
  if (['1007', '1008'].includes(prefix)) return profiles.pharmacy
  if (['0701', '0712'].includes(prefix)) return profiles.mathematics
  if (prefix === '0703') return profiles.chemical
  if (prefix === '0710') return profiles.life
  if (prefix === '0711') return profiles.psychology
  if (['0705', '0706', '0707', '0708', '0709'].includes(prefix)) return profiles.geography
  if (prefix === '0809' || major.name === '区块链工程') return profiles.computing
  if (['0803', '0807'].includes(prefix) || major.name === '光电信息科学与工程') return profiles.electronics
  if (['0805', '0806', '0808', '0822'].includes(prefix) || /能源|储能|辐射防护/.test(major.name)) return profiles.energy
  if (prefix === '0804') return profiles.materials
  if (['0810', '0811', '0812', '0818', '0825', '0828', '0829'].includes(prefix) || major.name === '测绘工程') return profiles.built
  if (['0813', '0816', '0817', '0827', '0830', '0836'].includes(prefix)) return profiles.process
  if (code.startsWith('02') || code.startsWith('12')) return profiles.business
  if (prefix === '0301') return profiles.law
  if (code.startsWith('03')) return profiles.social
  if (prefix === '0401') return profiles.education
  if (prefix === '0502') return profiles.language
  if (prefix === '0503') return profiles.media
  return profiles[fallback[major.category]]
}

export function getMajorApplications(major: Major): string {
  const sentences = major.description.match(/[^。！？]+[。！？]?/g) ?? []
  return sentences.find(sentence => /毕业|就业|所学知识可用于/.test(sentence)) ?? getMajorExploration(major).direction
}
